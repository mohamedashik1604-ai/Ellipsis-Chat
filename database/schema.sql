-- Ellipsis Chat / NCATS AGM - Oracle database schema
CREATE USER sandbox IDENTIFIED BY "PASSWORD"
    DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE TO sandbox;

CREATE TABLE app_users (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    email VARCHAR2(255 CHAR) NOT NULL,
    password_hash VARCHAR2(255 CHAR) NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT app_users_pk PRIMARY KEY (id),
    CONSTRAINT app_users_email_un UNIQUE (email)
);
CREATE TABLE conversations (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id NUMBER NOT NULL,
    title VARCHAR2(200 CHAR),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT conversations_pk PRIMARY KEY (id),
    CONSTRAINT fk_conv_user FOREIGN KEY(user_id) REFERENCES app_users(id) ON DELETE CASCADE
);
CREATE INDEX ix_conv_user ON conversations(user_id);
CREATE TABLE messages (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    conversation_id NUMBER NOT NULL,
    role VARCHAR2(20 CHAR) NOT NULL,
    content CLOB NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT messages_pk PRIMARY KEY (id),
    CONSTRAINT ck_msg_role CHECK (role IN ('user','assistant','system')),
    CONSTRAINT fk_msg_conv FOREIGN KEY(conversation_id) REFERENCES conversations(id) ON DELETE CASCADE
);
CREATE INDEX ix_msg_conv ON messages(conversation_id,id);
CREATE TABLE documents (
    doc_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    source_name VARCHAR2(300 CHAR) NOT NULL,
    file_name VARCHAR2(300 CHAR) NOT NULL,
    file_sha256 CHAR(64),
    page_count NUMBER(6),
    version_note VARCHAR2(200 CHAR),
    ingested_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT documents_pk PRIMARY KEY (doc_id),
    CONSTRAINT documents_file_un UNIQUE(file_name,file_sha256)
);
CREATE TABLE doc_chunks (
    chunk_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    doc_id NUMBER NOT NULL,
    chunk_no NUMBER(6) NOT NULL,
    chapter VARCHAR2(300 CHAR),
    section VARCHAR2(500 CHAR),
    page_start NUMBER(6),
    page_end NUMBER(6),
    chunk_text CLOB NOT NULL,
    char_count NUMBER(7),
    embedding VECTOR(384,FLOAT32),
    embedding_model VARCHAR2(100 CHAR),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT doc_chunks_pk PRIMARY KEY(chunk_id),
    CONSTRAINT uq_doc_chunk UNIQUE(doc_id,chunk_no),
    CONSTRAINT fk_chunk_doc FOREIGN KEY(doc_id) REFERENCES documents(doc_id) ON DELETE CASCADE
);
CREATE INDEX ix_chunks_page ON doc_chunks(doc_id,page_start);
CREATE TABLE message_sources (
    message_id NUMBER NOT NULL,
    rank_no NUMBER(3) NOT NULL,
    chunk_id NUMBER NOT NULL,
    distance NUMBER(8,6),
    CONSTRAINT message_sources_pk PRIMARY KEY(message_id,rank_no),
    CONSTRAINT fk_ms_msg FOREIGN KEY(message_id) REFERENCES messages(id) ON DELETE CASCADE,
    CONSTRAINT fk_ms_chunk FOREIGN KEY(chunk_id) REFERENCES doc_chunks(chunk_id) ON DELETE CASCADE
);
CREATE INDEX ix_ms_chunk ON message_sources(chunk_id);
